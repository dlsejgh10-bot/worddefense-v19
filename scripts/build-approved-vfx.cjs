// Derive production drawing methods from approved sources, without mock setup or damage.
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const repo=path.resolve(process.argv[2] || path.join(__dirname,'..'));
const src=path.join(repo,'design/vfx_mock_v4'),dst=path.join(repo,'WordDefense/Resources/www/skill-vfx-v4');
fs.mkdirSync(dst,{recursive:true});
const read=n=>fs.readFileSync(path.join(src,n),'utf8');
const lines=(n,a,b)=>read(n).split(/\r?\n/).slice(a-1,b).join('\n');
const fake={S:{},E:{},U:{},frame(){}};
const box={window:{P3:fake},PM:{S:{ranger:{}}},EC6:[['#cfc8b8','#f4f0e6','#6d675c'],['#ff7a2e','#ffd27a','#a8321a'],['#3d8fe0','#bfe3ff','#1f5a9c'],['#8fdcff','#eafaff','#4f9ec0'],['#ffe03a','#fff7c2','#b08a10']]};
vm.createContext(box);for(const n of ['sc4a.js','sc4b.js','sc4c.js'])vm.runInContext(read(n),box);
const selected=['ranger_skill','archer_skill','warrior','miner_skill','artillery_skill','mage_meteor','buffer','zone_energy_orb'];
const header='// Approved v4 renderers. Generated by scripts/build-approved-vfx.cjs. Mock init/damage deliberately excluded.\n';
let out=header+lines('fx4.js',1,60).replace(/const _pn[^\n]*\nperformance.now[^\n]*\n/,'')+'\n})();\n'+lines('fx4.js',75,126)+'\n';
out+='(() => { const P=window.P3,S=P.S,E=P.E,seg=P.seg,cl=P.cl,H=P.H,INK=P.INK;\n';
out+=lines('sc4a.js',4,4)+'\n'+lines('sc4a.js',6,6)+'\n';
out+='const hpDrop=()=>{},knock=()=>{}; P.hit=()=>{};P.dmg=()=>{};P.shake=()=>{};P.atk=(T,t,tf,dur=.5)=>{const st=tf-.4*dur;T.animDur=dur;T.animT=t>=st&&t<st+dur?t-st:-1;};\n';
out+=lines('sc4a.js',14,19)+'\n'+lines('sc4a.js',47,47)+'\n'+lines('sc4a.js',236,266)+'\n';
for(const key of selected){const scene=fake.S[key];out+=`S.${key}={\n`+Object.entries(scene).filter(([k])=>k!=='init').map(([k,v])=>typeof v==='function'?v.toString():`${k}:${JSON.stringify(v)}`).join(',\n')+'\n};\n';}
// Sniper top() closes over its element palette, retain that closure explicitly.
out+='const sniperColors='+JSON.stringify(box.EC6)+';\n';
for(const [i,key]of ['phys','fire','water','ice','lightning'].entries()){
 const s=fake.S['sniper_ult_'+key],c=box.EC6[i];
 out+=`{const C=${JSON.stringify({m:i===1?'#ff5a1e':c[0],l:i===1?'#ff9a50':i===2?'#8cc4ff':c[1],d:c[2],n:c[0]})};S.sniper_ult_${key}={dur:3.2,${s.update.toString()},${s.top.toString()}};}\n`;
}
out+='})();\n';
// Arbitrary shot counts use native V.n(L), while keeping the approved pose sequence.
out=out.replaceAll('this.shots[4]','this.shots[this.shots.length-1]').replaceAll('this.ts[9]','this.ts[this.ts.length-1]');
out=out.replace(/P\.dmg\([^;\n]*\);/g,'');
// No preview damage strings or mock globals are allowed in the production renderer.
fs.writeFileSync(path.join(dst,'approved.js'),out);
fs.copyFileSync(path.join(src,'slamvfx.js'),path.join(dst,'slamvfx.js'));
fs.cpSync(path.join(src,'sheets'),path.join(dst,'sheets'),{recursive:true});
console.log('Generated approved.js and copied unchanged PNG sources to',dst);
